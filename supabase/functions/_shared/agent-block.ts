// The delimited block Krill Lab writes into the files AI agents read (AGENTS.md, CLAUDE.md…)
// and replaces without touching the rest. No dependencies: used by both the App and the CLI.
import { RULES_PATH } from "./rules-format.ts";

const START = "<!-- krill-lab:start -->";
const END = "<!-- krill-lab:end -->";
export const AGENT_FILES = ["AGENTS.md", "CLAUDE.md", ".cursorrules", ".github/copilot-instructions.md"];
export const DEFAULT_AGENT_FILE = "AGENTS.md"; // the standard most agents read

const HEADING = "## Team rules";
const NOTE = `Generated by Krill Lab from \`${RULES_PATH}\`. To change these rules, edit that file, not this block.`;

export function buildBlock(rulesMarkdown: string): string {
  // The block starts at the first rule: the file's title and intro are left out
  const firstRule = rulesMarkdown.search(/^## /m);
  const rules = (firstRule >= 0 ? rulesMarkdown.slice(firstRule) : rulesMarkdown)
    .replace(/^## /gm, "### ")
    .trim();
  return `${START}\n${HEADING}\n\n${NOTE}\n\n${rules}\n${END}`;
}

export function upsertBlock(existing: string, block: string): string {
  const start = existing.indexOf(START);
  const end = existing.indexOf(END);
  if (start >= 0 && end > start) {
    return existing.slice(0, start) + block + existing.slice(end + END.length);
  }
  return `${existing.trimEnd()}\n\n${block}\n`;
}
